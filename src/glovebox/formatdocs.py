"""
Generated documentation of the standard CSV format and the presets (design D11).

``uv run python -m glovebox.formatdocs`` writes ``docs/user/standard-format.md``,
``docs/user/standard-format.datapackage.json`` and ``docs/user/presets.md``;
with ``--check`` it writes nothing and exits non-zero if a file is out of date.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from pathlib import Path

from glovebox.importers.presets import KEY_TABLE, shipped_presets
from glovebox.standard import (
    EXAMPLE_RECORDS,
    RECORD_FIELDS,
    REQUIRED_ALWAYS,
    REQUIRED_EXPENSE,
    REQUIRED_REFUEL,
    TABLES,
    StandardField,
    datapackage,
)

DOCS_DIR = Path(__file__).resolve().parents[2] / "docs" / "user"
STANDARD_MD = "standard-format.md"
DATAPACKAGE_JSON = "standard-format.datapackage.json"
PRESETS_MD = "presets.md"

COMMAND = "uv run python -m glovebox.formatdocs"
HEADER = f"<!-- Generated by `{COMMAND}`. Do not edit by hand. -->\n\n"

_TABLE_HEADINGS = {
    "records": ("records.csv", "Refuels and expenses. Used by every standard import and export."),
    "vehicles": (
        "vehicles.csv",
        "Optional. Vehicle details; see [Optional tables](#optional-tables-vehicles-stations-and-reminders).",
    ),
    "stations": (
        "stations.csv",
        "Optional. Station details and stations without refuels; see "
        "[Optional tables](#optional-tables-vehicles-stations-and-reminders).",
    ),
    "reminders": (
        "reminders.csv",
        "Optional. Date reminders of the vehicles; see "
        "[Optional tables](#optional-tables-vehicles-stations-and-reminders).",
    ),
}

_REQUIRED_TEXT = {
    REQUIRED_ALWAYS: "always",
    REQUIRED_REFUEL: "refuel rows",
    REQUIRED_EXPENSE: "expense rows",
}

_CONVERT_SCRIPT = '''\
import csv

with open("my-export.csv", newline="", encoding="utf-8") as src, \\
        open("records.csv", "w", newline="", encoding="utf-8") as dst:
    out = csv.DictWriter(dst, ["type", "vehicle", "date", "odometer_km", "fuel_l", "total"])
    out.writeheader()
    for row in csv.DictReader(src):
        out.writerow({
            "type": "refuel", "vehicle": "Golf",
            "date": row["Date"],               # must be YYYY-MM-DD
            "odometer_km": row["Odometer"],
            "fuel_l": row["Litres"].replace(",", "."),
            "total": row["Cost"].replace(",", "."),
        })
'''


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _unit(field: StandardField) -> str:
    return f"`{field.unit}`" if field.unit else ""


def _required(field: StandardField) -> str:
    return _REQUIRED_TEXT.get(field.required, "no")


def _description(field: StandardField) -> str:
    parts = [field.description]
    if field.rule:
        parts.append(field.rule)
    if field.enum and field.type == "enum":
        parts.append("One of " + ", ".join(f"`{v}`" for v in field.enum) + ".")
    if field.default is not None:
        parts.append(f"Empty means `{field.default}`.")
    return _cell(" ".join(parts))


def _field_table(fields: tuple[StandardField, ...], with_applies: bool) -> list[str]:
    head = ["Column", "Type", "Unit", "Required"]
    if with_applies:
        head.append("Applies to")
    head += ["Description", "Example"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for f in fields:
        cells = [f"`{f.name}`", f.type, _unit(f), _required(f)]
        if with_applies:
            cells.append(" and ".join(f.applies_to) if len(f.applies_to) < 2 else "both")
        cells += [_description(f), f"`{f.example}`" if f.example else ""]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def example_csv() -> str:
    """The example ``records.csv`` as written by Glovebox (CRLF line ends)."""
    names = [f.name for f in RECORD_FIELDS]
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, names, lineterminator="\r\n")
    writer.writeheader()
    for row in EXAMPLE_RECORDS:
        writer.writerow({name: row.get(name, "") for name in names})
    return buffer.getvalue()


def render_standard_markdown() -> str:
    """The page ``docs/user/standard-format.md``."""
    lines = [
        "# Standard CSV format",
        "",
        "The standard format is Glovebox's own, fully documented CSV layout. "
        "Export it to move your data, or convert another app's export into it "
        "and import it with the **Glovebox** preset. "
        "Importing from another app directly is described in [Import](import.md); "
        "the export side is in [Export and backup](export.md).",
        "",
        "A machine-readable description (a Data Package with one Table Schema per "
        f"table) is available as [{DATAPACKAGE_JSON}]({DATAPACKAGE_JSON}). "
        "A full backup contains the same description as `datapackage.json`.",
        "",
        "## Conventions",
        "",
        "- **File:** RFC 4180 CSV. Comma delimiter, `\"` quoting, CRLF line ends, "
        "one header row. UTF-8 without a byte order mark when written; a BOM is "
        "accepted when read.",
        "- **Dates and times:** dates are `YYYY-MM-DD`, times `HH:MM` "
        "(`HH:MM:SS` is accepted when reading).",
        "- **Numbers:** dot as decimal separator, no thousands separator.",
        "- **Booleans:** `true` or `false`.",
        "- **Empty cells:** an empty cell means no value. Columns that do not "
        "apply to a row's type stay empty.",
        "- **Units:** distances in kilometres, volumes in litres, money as a "
        "decimal number in the currency named in `currency`. The unit is part "
        "of the column name where a column has one.",
        "- **Currency:** a non-empty `currency` that differs from the app "
        "currency makes that row an error on import.",
        "- **Precision on export:** `fuel_l` and `price_per_l` with 3 decimals, "
        "`total` with 2 decimals, `odometer_km` without trailing zeros.",
        "",
        "### Rules per record type",
        "",
        "- `type` is `refuel` or `expense`. `type`, `vehicle` and `date` are "
        "required on every row.",
        "- A refuel needs `odometer_km` and two of `fuel_l`, `price_per_l` and "
        "`total`; the third is calculated.",
        "- An expense needs `title` and a `total` greater than 0. `coverage_start` "
        "and `coverage_end` are set both or neither.",
        "- Records refer to vehicles by name and to stations by name and location.",
        "",
    ]
    lines += [
        "## Optional tables: vehicles, stations and reminders",
        "",
        "`records.csv` alone is enough. To bring vehicle and station details "
        "and reminders along, put `vehicles.csv`, `stations.csv` and/or "
        "`reminders.csv` next to `records.csv` in a ZIP file, or in a ZIP of several CSV files, and import the ZIP. "
        "The ZIP does not need a `datapackage.json`.",
        "",
        "- A vehicle or station that does not exist yet is created with all the "
        "details given.",
        "- A vehicle (matched by `name`) or station (matched by `name` and "
        "`location`) that already exists is only completed: empty details are "
        "filled and nothing is overwritten.",
        "- The import preview lists which vehicles and stations will be created "
        "or filled before you confirm.",
        "- `stations.csv` can list stations that have no refuels yet.",
        "- A reminder in `reminders.csv` whose `uid` already exists is skipped as "
        "a duplicate. Reminders refer to vehicles by name, like records. The "
        "link to an expense and the calendar state are not part of the file.",
        "- A full backup is exactly this, plus `datapackage.json`: it is made "
        "on the export page and restored on the import page like any other ZIP.",
        "",
    ]
    for name, fields in TABLES.items():
        title, note = _TABLE_HEADINGS[name]
        lines += [f"## `{title}`", "", note, ""]
        lines += _field_table(fields, with_applies=name == "records")
        lines.append("")
    lines += [
        "## Example",
        "",
        "One refuel and one expense (`records.csv`):",
        "",
        "```csv",
        *example_csv().replace("\r\n", "\n").rstrip("\n").split("\n"),
        "```",
        "",
        "## Convert your own export",
        "",
        "Any CSV that follows the tables above can be imported with the "
        "**Glovebox** preset. You only need the columns that are "
        "required for your rows.",
        "",
        "### With a spreadsheet",
        "",
        "1. Open your export in a spreadsheet program.",
        "2. Add a `type` column filled with `refuel` (or `expense`) and a "
        "`vehicle` column with the vehicle name.",
        "3. Rename or move columns so that the headers match the tables above. "
        "Delete columns you do not need.",
        "4. Make sure dates are `YYYY-MM-DD` and numbers use a dot as the "
        "decimal separator, with no thousands separator.",
        "5. Save as CSV (UTF-8, comma delimited) and import it with the "
        "**Glovebox** preset.",
        "",
        "### With a script",
        "",
        "This Python example uses only the standard `csv` module. Adjust the "
        "file name and the source column names to your export.",
        "",
        "```python",
        *_CONVERT_SCRIPT.rstrip("\n").split("\n"),
        "```",
        "",
        "If your export needs only renamed columns or another date or number "
        "format, a custom preset is easier than conversion: see [Presets](presets.md).",
        "",
    ]
    return HEADER + "\n".join(lines)


def render_datapackage_json() -> str:
    """The descriptor ``docs/user/standard-format.datapackage.json``."""
    return json.dumps(datapackage(), indent=2, ensure_ascii=False) + "\n"


def render_presets_markdown() -> str:
    """The page ``docs/user/presets.md``."""
    lines = [
        "# Presets",
        "",
        "A preset describes how one CSV layout maps onto the standard fields: "
        "which source column feeds which field, and how dates, numbers and "
        "units are written. Presets are TOML files. You can create and edit "
        "them in the app (**Manage → Presets**; a mapping is saved from the import preview); this page lists every key and "
        "the presets that ship with Glovebox. For the target fields see "
        "[Standard CSV format](standard-format.md).",
        "",
        "## Shipped presets",
        "",
    ]
    presets = shipped_presets()
    if presets:
        lines += [
            "| Id | Name | Verified | Export | Note |",
            "|---|---|---|---|---|",
        ]
        for p in presets:
            lines.append(
                f"| `{p.id}` | {_cell(p.name)} | {'yes' if p.verified else 'no'} "
                f"| {'yes' if p.export else 'no'} | {_cell(' '.join(p.note.split()))} |"
            )
    else:
        lines.append("No presets are shipped.")
    lines += [
        "",
        "## Keys",
        "",
        "| Key | Type | Allowed values | Default | Description |",
        "|---|---|---|---|---|",
    ]
    for k in KEY_TABLE:
        lines.append(
            f"| `{k.path}` | {k.type} | {_cell(k.allowed)} | {_cell(k.default)} "
            f"| {_cell(k.description)} |"
        )
    lines.append("")
    return HEADER + "\n".join(lines)


def rendered_files() -> dict[str, str]:
    """File name -> generated content."""
    return {
        STANDARD_MD: render_standard_markdown(),
        DATAPACKAGE_JSON: render_datapackage_json(),
        PRESETS_MD: render_presets_markdown(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if a file is out of date")
    parser.add_argument("--docs-dir", type=Path, default=DOCS_DIR)
    args = parser.parse_args(argv)
    stale = []
    for name, content in rendered_files().items():
        path = args.docs_dir / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(name)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        print(f"Out of date: {', '.join(stale)}. Run: {COMMAND}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
